// Deploy helper: the Worker serves the app's own pages, scripts and styles itself (embedded in src/static-embed.js),
// and Cloudflare static assets only hold the big, rarely-changing vendor files (dist-assets/vendor).
// That keeps a deploy from having to upload changed page files as assets.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, cpSync, rmSync } from 'node:fs';
import { join, relative } from 'node:path';
const root = new URL('..', import.meta.url).pathname, pub = join(root, 'public');
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = {};
for (const p of walk(pub)) {
  const rel = '/' + relative(pub, p).split('\\').join('/');
  if (rel.startsWith('/vendor/')) continue;
  files[rel] = readFileSync(p, 'utf8');
}
writeFileSync(join(root, 'src/static-embed.js'), '// Generated by scripts/embed-static.mjs. Do not edit.\nexport default ' + JSON.stringify(files) + ';\n');
rmSync(join(root, 'dist-assets'), { recursive: true, force: true });
mkdirSync(join(root, 'dist-assets'), { recursive: true });
cpSync(join(pub, 'vendor'), join(root, 'dist-assets/vendor'), { recursive: true });
console.log('embedded', Object.keys(files).length, 'files:', Object.keys(files).join(' '));
